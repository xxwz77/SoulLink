param([Parameter(Mandatory=$true)][string]$Root, [Parameter(Mandatory=$true)][string]$Out)
$ErrorActionPreference = 'Stop'
$src = Join-Path $Root 'docs\web-index.html'
if (-not (Test-Path -LiteralPath $src)) { throw '找不到 docs/web-index.html，网页兜底内容无法生成。' }
$body = [IO.File]::ReadAllText($src, [Text.Encoding]::UTF8)
$triple = [string]([char]34) + [string]([char]34) + [string]([char]34)
if ($body.Contains($triple)) { throw 'docs/web-index.html 含连续三个双引号，无法生成 raw string literal。' }
$dir = Split-Path -Parent $Out
if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
$nl = [Environment]::NewLine
$content = '// <auto-generated> Generated from docs/web-index.html. Do not edit.' + $nl
$content += 'namespace SoulLink.Services' + $nl + '{' + $nl
$content += '    internal static partial class WebPages' + $nl + '    {' + $nl
$content += '        public const string Index = ' + $triple + $nl + $body + $nl + $triple + ';' + $nl
$content += '    }' + $nl + '}' + $nl
[IO.File]::WriteAllText($Out, $content, (New-Object Text.UTF8Encoding($false)))
Write-Output ('Generated WebPages.Index from docs/web-index.html → ' + $Out)
